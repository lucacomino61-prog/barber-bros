/** the same page in a given language: '/' is Albanian, '/en/' English */
export const localePath = (lang: Lang, path: string) => (lang === 'en' ? `/en${path}` : path);

/** "a, b and c" */
export const listJoin = (items: string[], lang: Lang) =>
  items.length < 2 ? items.join('') : `${items.slice(0, -1).join(', ')} ${lang === 'en' ? 'and' : 'dhe'} ${items[items.length - 1]}`;

